const TRANSLATIONS = Object.freeze({
  en: ENGLISH,
  ...CORE_TRANSLATIONS,
});

export const SUPPORTED_LOCALES = Object.freeze(['en', 'es', 'fr', 'de', 'ar']);
export const RTL_LOCALES = Object.freeze(['ar', 'fa', 'he', 'ur']);

export function resolveLocale(locale) {
  const normalized = String(locale || '').toLowerCase().split('-')[0];
  return SUPPORTED_LOCALES.includes(normalized) ? normalized : 'en';
}

export function isRtlLocale(locale) {
  return RTL_LOCALES.includes(resolveLocale(locale));
}

export function localeLabel(locale) {
  const language = resolveLocale(locale);
  return ENGLISH[`language.${language}`] || language;
}

function replaceVariables(template, variables, formatNumber) {
  return String(template).replace(/\{(\w+)\}/g, (_, name) => {
    const value = variables[name];
    if (value == null) return `{${name}}`;
    return name === 'count' && typeof value === 'number' ? formatNumber(value) : String(value);
  });
}

export function createI18n(locale = 'en') {
  const language = resolveLocale(locale);
  const table = { ...ENGLISH, ...(TRANSLATIONS[language] || {}) };
  const intlLocale = language === 'en' ? 'en-US' : language;
  const dateTime = new Intl.DateTimeFormat(intlLocale, { dateStyle: 'medium', timeStyle: 'short' });
  const relative = typeof Intl.RelativeTimeFormat === 'function'
    ? new Intl.RelativeTimeFormat(intlLocale, { numeric: 'auto' }) : null;
  const pluralRules = typeof Intl.PluralRules === 'function' ? new Intl.PluralRules(intlLocale) : null;
  const formatNumber = (value, options = {}) => new Intl.NumberFormat(intlLocale, options).format(Number(value) || 0);
  const formatTemplate = (key, variables = {}) => replaceVariables(table[key] || ENGLISH[key] || key, variables, formatNumber);
  return {
    locale: language,
    intlLocale,
    direction: isRtlLocale(language) ? 'rtl' : 'ltr',
    t(key, variables = {}) {
      return formatTemplate(key, variables);
    },
    tp(key, count, variables = {}) {
      const category = pluralRules?.select(Number(count) || 0) || ((Number(count) || 0) === 1 ? 'one' : 'other');
      const pluralKey = `${key}.${category}`;
      return formatTemplate(pluralKey in table || pluralKey in ENGLISH ? pluralKey : `${key}.other`, { ...variables, count });
    },
    formatNumber,
    formatPercent(value, maximumFractionDigits = 0) {
      return formatNumber(Math.max(0, Math.min(100, Number(value) || 0)) / 100, { style: 'percent', maximumFractionDigits });
    },
    formatCurrency(value, currency = 'USD', maximumFractionDigits = 2) {
      return formatNumber(value, { style: 'currency', currency, maximumFractionDigits });
    },
    formatDate(iso, options = { dateStyle: 'medium' }) {
      const date = new Date(iso);
      return Number.isFinite(date.getTime()) ? new Intl.DateTimeFormat(intlLocale, options).format(date) : table['app.unavailable'];
    },
    formatTime(iso, options = { hour: 'numeric', minute: '2-digit' }) {
      const date = new Date(iso);
      return Number.isFinite(date.getTime()) ? new Intl.DateTimeFormat(intlLocale, options).format(date) : table['app.unavailable'];
    },
    formatDateTime(iso) {
      const date = new Date(iso);
      return Number.isFinite(date.getTime()) ? dateTime.format(date) : table['app.unavailable'];
    },
    formatRelative(iso) {
      const ms = Date.now() - new Date(iso).getTime();
      if (!Number.isFinite(ms)) return table['app.unavailable'];
      const minutes = Math.round(Math.abs(ms) / 60_000);
      if (!relative) return `${formatNumber(minutes)}m`;
      if (minutes < 60) return relative.format(ms <= 0 ? minutes : -minutes, 'minute');
      const hours = Math.round(minutes / 60);
      if (hours < 24) return relative.format(ms <= 0 ? hours : -hours, 'hour');
      const days = Math.round(hours / 24);
      return relative.format(ms <= 0 ? days : -days, 'day');
    },
  };
}

function localizeElement(i18n, root) {
  if (!root?.querySelectorAll) return;
  const elements = [];
  if (root.dataset?.i18n || root.dataset?.i18nTitle || root.dataset?.i18nAriaLabel || root.dataset?.i18nPlaceholder) elements.push(root);
  elements.push(...root.querySelectorAll('[data-i18n], [data-i18n-title], [data-i18n-aria-label], [data-i18n-placeholder]'));
  for (const element of elements) {
    if (element.dataset.i18n) element.textContent = i18n.t(element.dataset.i18n);
    if (element.dataset.i18nTitle) element.setAttribute('title', i18n.t(element.dataset.i18nTitle));
    if (element.dataset.i18nAriaLabel) element.setAttribute('aria-label', i18n.t(element.dataset.i18nAriaLabel));
    if (element.dataset.i18nPlaceholder) element.setAttribute('placeholder', i18n.t(element.dataset.i18nPlaceholder));
  }
  if (root.dataset) {
    root.dataset.locale = i18n.locale;
    root.setAttribute('lang', i18n.locale);
    root.setAttribute('dir', i18n.direction);
  }
}

export function applyElementLocale(i18n, root = globalThis.document?.body) {
  localizeElement(i18n, root);
  return root;
}

export function applyDocumentLocale(i18n, doc = globalThis.document) {
  if (!doc?.documentElement) return doc;
  doc.documentElement.lang = i18n.locale;
  doc.documentElement.dir = i18n.direction;
  localizeElement(i18n, doc);
  return doc;
}
